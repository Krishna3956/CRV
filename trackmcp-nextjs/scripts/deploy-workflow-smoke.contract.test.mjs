test("distributed rate-limit enablement preserves and verifies the App Runner configuration", () => {
  assert.match(distributedWorkflow, /workflow_dispatch/);
  assert.match(distributedWorkflow, /configure-aws-credentials@v4/);
  assert.match(distributedWorkflow, /describe-service/);
  assert.match(distributedWorkflow, /RuntimeEnvironmentVariables/);
  assert.match(distributedWorkflow, /TRACKMCP_RATE_LIMIT_MODE = \"supabase\"/);
  assert.match(distributedWorkflow, /update-service/);
  assert.match(distributedWorkflow, /narrowly scoped apprunner:UpdateService grant/);
  assert.match(distributedWorkflow, /list-operations/);
  assert.match(distributedWorkflow, /TRACKMCP_RATE_LIMIT_MODE=supabase/);
  assert.match(distributedWorkflow, /distributed-rate-limit-mode/);
  assert.match(distributedWorkflow, /"outcome":"blocked_iam"/);
  assert.match(distributedWorkflow, /"required_action":"apprunner:UpdateService"/);
  assert.match(distributedWorkflow, /"outcome":"enabled"/);
  assert.doesNotMatch(distributedWorkflow, /SUPABASE_SERVICE_ROLE_KEY|TRACKMCP_REFRESH_WORKER_SECRET/);
});

test("production key lifecycle workflow is manual, write-gated, and redacted", () => {
  assert.match(lifecycleWorkflow, /workflow_dispatch/);
  assert.match(lifecycleWorkflow, /TRACKMCP_KEY_LIFECYCLE_CONFIRM/);
  assert.match(lifecycleWorkflow, /confirm_write:/);
  assert.match(lifecycleWorkflow, /inputs\.confirm_write && 'true'/);
  assert.match(lifecycleWorkflow, /TRACKMCP_LIFECYCLE_COOKIE/);
  assert.match(lifecycleWorkflow, /TRACKMCP_LIFECYCLE_KEY_ID/);
  assert.match(lifecycleWorkflow, /missing configured repository secrets/);
  assert.match(lifecycleWorkflow, /actions\/upload-artifact@v4/);
  assert.doesNotMatch(lifecycleWorkflow, /echo .*TRACKMCP_LIFECYCLE_KEY|console\.log/);
});

