import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

const workflow = await readFile(new URL("../../.github/workflows/deploy.yml", import.meta.url), "utf8");
const distributedWorkflow = await readFile(new URL("../../.github/workflows/enable-distributed-rate-limit.yml", import.meta.url), "utf8");

test("App Runner deployment performs a redacted read-only smoke after RUNNING", () => {
  assert.match(workflow, /timeout-minutes: 35/);
  assert.match(workflow, /deadline=\$\(\(SECONDS \+ 1200\)\)/);
  assert.match(workflow, /while \(\( SECONDS < deadline \)\); do/);
  assert.match(workflow, /timeout 30s aws apprunner start-deployment/);
  assert.match(workflow, /timeout 15m docker build/);
  assert.match(workflow, /timeout 10m docker push/);
  assert.match(workflow, /timeout 30s aws apprunner list-operations/);
  assert.match(workflow, /timeout 30s aws apprunner describe-service/);
  assert.match(workflow, /actions\/setup-node@v4/);
  assert.match(workflow, /deploy_ref:/);
  assert.match(workflow, /deploy_ref must be a full immutable 40-character commit SHA/);
  assert.match(workflow, /ref: \$\{\{ github\.sha \}\}/);
  assert.match(workflow, /Select immutable rollback revision/);
  assert.match(workflow, /git fetch --no-tags --depth=1 origin "\$REQUESTED_DEPLOY_REF"/);
  assert.match(workflow, /git checkout --detach "\$REQUESTED_DEPLOY_REF"/);
  assert.match(workflow, /TRACKMCP_DEPLOY_SHA=\$DEPLOY_SHA/);
  assert.match(workflow, /actions\/setup-python@v5/);
  assert.match(workflow, /Install production-smoke dependencies/);
  assert.match(workflow, /Install Python package build dependency/);
  assert.match(workflow, /python3 -m pip install build/);
  assert.match(workflow, /Run release gate before deployment/);
  assert.match(workflow, /npm run test:release-gate/);
  assert.match(workflow, /Verify deployment tag resolves to the candidate image/);
  assert.match(workflow, /deploy-tag-push\.log/);
  assert.match(workflow, /candidate-tag-push\.log/);
  assert.doesNotMatch(workflow, /ecr describe-images/);
  assert.match(workflow, /TRACKMCP_DEPLOYED_IMAGE_DIGEST/);
  assert.match(workflow, /TRACKMCP_SMOKE_IMAGE_DIGEST/);
  assert.match(workflow, /TRACKMCP_DEPLOYMENT_OPERATION_ID=\$OP_ID/);
  assert.match(workflow, /App Runner operation IDs are opaque service identifiers/);
  assert.match(workflow, /TRACKMCP_DEPLOYMENT_OPERATION_ID/);
  assert.match(workflow, /list-operations/);
  assert.match(workflow, /OperationSummaryList\[\?Id=='\$TRACKMCP_DEPLOYMENT_OPERATION_ID'\]\.Status/);
  assert.match(workflow, /SUCCEEDED/);
  assert.match(workflow, /ROLLBACK_FAILED/);
  assert.match(workflow, /Run read-only production smoke/);
  assert.match(workflow, /SERVICE_HOST=\$\(timeout 30s aws apprunner describe-service[\s\S]*Service\.ServiceUrl/);
  assert.match(workflow, /ORIGIN=\"https:\/\/\$\{SERVICE_HOST\}\"/);
  assert.match(workflow, /valid service hostname/);
  assert.match(workflow, /TRACKMCP_PRODUCTION_SMOKE_CONFIRM=I_UNDERSTAND_PRODUCTION_SMOKE/);
  assert.match(workflow, /TRACKMCP_SMOKE_CANDIDATE_SHA="\$TRACKMCP_DEPLOY_SHA"/);
  assert.match(workflow, /npm run smoke:production-pilot/);
  assert.match(workflow, /Audit runtime safety flags/);
  assert.match(workflow, /RuntimeEnvironmentVariables/);
  assert.match(workflow, /TRACKMCP_RATE_LIMIT_MODE is invalid/);
  assert.match(workflow, /fact writes require TRACKMCP_RATE_LIMIT_MODE=supabase/);
  assert.match(workflow, /trackmcp-runtime-flags\.json/);
  assert.match(workflow, /Upload redacted production smoke evidence/);
  assert.doesNotMatch(workflow, /TRACKMCP_SMOKE_ALLOW_WRITE=true/);
});

test("distributed rate-limit enablement preserves and verifies the App Runner configuration", () => {
  assert.match(distributedWorkflow, /workflow_dispatch/);
  assert.match(distributedWorkflow, /configure-aws-credentials@v4/);
  assert.match(distributedWorkflow, /describe-service/);
  assert.match(distributedWorkflow, /RuntimeEnvironmentVariables/);
  assert.match(distributedWorkflow, /TRACKMCP_RATE_LIMIT_MODE = \"supabase\"/);
  assert.match(distributedWorkflow, /update-service/);
  assert.match(distributedWorkflow, /narrowly scoped apprunner:UpdateService grant/);
  assert.match(distributedWorkflow, /list-operations/);
  assert.match(distributedWorkflow, /TRACKMCP_RATE_LIMIT_MODE=supabase/);
  assert.match(distributedWorkflow, /distributed-rate-limit-mode/);
  assert.match(distributedWorkflow, /"outcome":"blocked_iam"/);
  assert.match(distributedWorkflow, /"required_action":"apprunner:UpdateService"/);
  assert.match(distributedWorkflow, /"outcome":"enabled"/);
  assert.doesNotMatch(distributedWorkflow, /SUPABASE_SERVICE_ROLE_KEY|TRACKMCP_REFRESH_WORKER_SECRET/);
});
