import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

const source = await readFile(new URL("./production-auth-smoke.mjs", import.meta.url), "utf8");

test("authenticated production smoke is explicit, HTTPS-only, and secret-free in its report", () => {
  assert.match(source, /I_UNDERSTAND_PRODUCTION_AUTH_SMOKE/);
  assert.match(source, /parsed\.protocol !== "https:"/);
  assert.match(source, /parsed\.hostname === "trackmcp\.com"/);
  assert.match(source, /app\.trackmcp\.com/);
  assert.match(source, /awsapprunner\.com/);
  assert.match(source, /trustedHost/);
  assert.match(source, /workspace_scope_verified/);
  assert.match(source, /founderOsReadModels/);
  assert.match(source, /\/api\/v2\/protocol-activity/);
  assert.match(source, /authenticated workspace envelope/);
  assert.match(source, /forbiddenReadModelKeys/);
  assert.match(source, /privacy_projection_verified/);
  assert.match(source, /release_sha: process\.env\.TRACKMCP_AUTH_SMOKE_RELEASE_SHA/);
  assert.match(source, /legacyReadModels/);
  assert.match(source, /\/api\/v1\/analytics\?days=30/);
  assert.match(source, /\/api\/v1\/tool-quality\?days=30/);
  assert.match(source, /\/api\/v1\/traces\?session_id=/);
  assert.match(source, /conflicting_workspace_ignored/);
  assert.match(source, /prompt_arguments/);
  assert.match(source, /resource_contents/);
  assert.match(source, /action queue API-key denial/);
  assert.match(source, /revoked key negative auth/);
  assert.match(source, /both workspace IDs, and a revoked key are required/);
  assert.match(source, /Read-only authenticated scope checks/);
  assert.match(source, /Keys, workspace IDs, response bodies/);
  assert.match(source, /outcome: "failed"/);
  assert.match(source, /Redacted failure report/);
  assert.match(source, /TRACKMCP_AUTH_SMOKE_TIMEOUT_MS/);
  assert.match(source, /AbortSignal\.timeout\(requestTimeoutMs\)/);
  assert.match(source, /error\?\.name === "TimeoutError"/);
  assert.match(source, /error instanceof TypeError/);
  assert.doesNotMatch(source, /console\.log\([^\n]*keyA/);
  assert.doesNotMatch(source, /JSON\.stringify\([^\n]*(keyA|keyB|workspaceA|workspaceB)/);
});
